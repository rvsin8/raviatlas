import rd from '@/data/regions.json';
import cd from '@/data/conditions.json';
import dd from '@/data/drugs.json';
import generated from '@/data/relations.generated.json';
import type {Region,Condition,Drug,Mode,BodySex} from './types';
export const regions=rd.regions as Region[];
export const conditions=cd.conditions as Condition[];
export const drugs=dd.drugs as Drug[];
export const relations=generated as Record<string,{conditionIds:string[];regionIds:string[]}>;
export const regionById=Object.fromEntries(regions.map(r=>[r.id,r]));
export const conditionById=Object.fromEntries(conditions.map(c=>[c.id,c]));
export const drugById=Object.fromEntries(drugs.map(d=>[d.id,d]));
export const topRegions=regions.filter(r=>!r.parentId&&!['skin','systemic'].includes(r.id));
export const children=(id:string)=>regions.filter(r=>r.parentId===id);
export const within=(id:string,part:string)=>id===part||regionById[part]?.parentId===id;
export const conditionForBody=(c:Condition,body:BodySex)=>c.sex==='both'||c.sex===body;
export const withinBodyRegion=(id:string,part:string)=>within(id,part)||(id==='reproductive-organs'&&['uterus','ovaries','fallopian-tubes','prostate','testes'].includes(part));
export const regionConditions=(id:string,mode?:Mode,body?:BodySex)=>conditions.filter(c=>(!body||conditionForBody(c,body))&&(!mode||c.mode===mode)&&c.regionIds.some(r=>withinBodyRegion(id,r)));
export const drugRelationsFor=(id:string,body:BodySex)=>{const cs=conditions.filter(c=>c.drugIds.includes(id)&&conditionForBody(c,body));return {conditionIds:cs.map(c=>c.id),regionIds:[...new Set(cs.flatMap(c=>c.regionIds))]}};
